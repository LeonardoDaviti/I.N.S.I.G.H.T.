import { Suspense, lazy, useCallback, useEffect, useState, type ReactNode } from 'react';
import { RefreshCw } from 'lucide-react';
import { apiService } from '../services/api';
import type { Expert, ExpertRunResult, ExpertTopic, ExpertBriefingHistoryEntry } from '../services/api';
import { Button, Chip, Skeleton, StatusIcon, TextLink } from './ui';
import { plural } from '../lib/format';
import { formatIssueLong, formatIssueRange, formatIssueShort } from '../lib/issueDate';
import { cn } from '../lib/utils';

// react-markdown + rehype pulls a ~100 KB gz chunk. A track with no expert bound,
// or no briefing yet, must not pay for it, so it loads only when there is markdown.
const MarkdownRenderer = lazy(() => import('./ui/MarkdownRenderer'));

/**
 * The stored topic briefing for the expert bound to this folder, rendered inside
 * the folder itself instead of only on /experts.
 *
 * Read-only: it fetches the LATEST STORED briefing. It never triggers generation,
 * so opening a track costs zero model tokens.
 *
 * Mark IX: read like a newsletter issue, not a card. A dated issue header, the
 * briefing in the reading measure, the topics as a numbered plain list, and the
 * past issues as a lowercase date strip. Monochrome: the fallback stub is told
 * apart by a dashed chip and words, never by amber.
 */

function asArray<T>(value: unknown): T[] {
  return Array.isArray(value) ? (value as T[]) : [];
}

/** "fallback" is the deterministic stub, not analysis. The user must be able to tell. */
function GeneratorBadge({ generator }: { generator?: string | null }) {
  if (!generator) return null;
  if (generator === 'fallback') {
    return (
      <Chip
        variant="dashed"
        title="This text was assembled by a deterministic stub because no model ran. It is not analysis."
      >
        <StatusIcon status="backoff" />
        fallback stub, not model analysis
      </Chip>
    );
  }
  return (
    <span className="min-w-0 truncate" title={`Generated by ${generator}`}>
      via {generator}
    </span>
  );
}

function TopicItem({ topic, index }: { topic: ExpertTopic; index: number }) {
  const postCount = asArray<string>(topic.post_ids).length;
  return (
    <li className="grid grid-cols-[1.75rem_minmax(0,1fr)] gap-x-2 border-t border-line py-4 first:border-t-0 first:pt-0">
      <span aria-hidden="true" className="pt-px text-[0.8125rem] tabular-nums text-fg-3">
        {String(index + 1).padStart(2, '0')}
      </span>
      <div className="min-w-0">
        <h4 className="break-words font-semibold leading-[1.35] tracking-[-0.01em] text-fg [overflow-wrap:anywhere]">
          {topic.title || 'Untitled topic'}
          <span className="ml-2 whitespace-nowrap text-[0.8125rem] font-normal tabular-nums text-fg-3">
            {plural(postCount, 'post')}
          </span>
        </h4>
        {topic.summary && (
          <div className="mt-1.5 min-w-0 break-words text-fg-2 [overflow-wrap:anywhere]">
            <Suspense fallback={<p className="whitespace-pre-wrap">{topic.summary}</p>}>
              <MarkdownRenderer content={topic.summary} />
            </Suspense>
          </div>
        )}
      </div>
    </li>
  );
}

/** The quiet box the two "nothing to read" states share. */
function QuietNote({ children, className }: { children: ReactNode; className?: string }) {
  return (
    <div className={cn('rounded-md border border-dashed border-line-strong px-4 py-3 text-[0.875rem] text-fg-2', className)}>
      {children}
    </div>
  );
}

export default function TrackBriefingPanel({
  folderId,
  className = '',
}: {
  folderId: string;
  className?: string;
}) {
  const [expert, setExpert] = useState<Expert | null>(null);
  const [briefing, setBriefing] = useState<ExpertRunResult | null>(null);
  const [history, setHistory] = useState<ExpertBriefingHistoryEntry[]>([]);
  const [selectedDate, setSelectedDate] = useState<string | null>(null);
  const [loading, setLoading] = useState(true);
  const [switching, setSwitching] = useState(false);
  const [open, setOpen] = useState(true);

  const load = useCallback(async () => {
    // No folder means no binding to look up; never leave the panel on a skeleton.
    if (!folderId) {
      setLoading(false);
      return;
    }
    setLoading(true);
    setExpert(null);
    setBriefing(null);
    // /api/experts has no folder filter; the binding is expert.folder_id.
    const res = await apiService.getExperts();
    const bound = asArray<Expert>(res?.experts).find((e) => e?.folder_id === folderId) || null;
    setExpert(bound);
    if (!bound) {
      setLoading(false);
      return;
    }
    const [result, past] = await Promise.all([
      apiService.getExpertBriefing(bound.id),
      apiService.getExpertBriefingHistory(bound.id),
    ]);
    setBriefing(result ?? null);
    const entries = asArray<ExpertBriefingHistoryEntry>(past?.briefings);
    setHistory(entries);
    setSelectedDate(entries[0]?.end_date ?? null);
    setLoading(false);
  }, [folderId]);

  /** Load one past briefing by its end date. Cached server-side; costs no LLM call. */
  const selectDate = useCallback(
    async (endDate: string) => {
      if (!expert || endDate === selectedDate) return;
      setSwitching(true);
      const result = await apiService.getExpertBriefing(expert.id, endDate);
      if (result?.success) {
        setBriefing(result);
        setSelectedDate(endDate);
      }
      setSwitching(false);
    },
    [expert, selectedDate],
  );

  useEffect(() => {
    void load();
  }, [load]);

  if (loading) {
    return (
      <div role="status" aria-busy="true" className={cn('space-y-3 border-b border-line pb-8', className)}>
        <span className="sr-only">Loading the track briefing</span>
        <Skeleton className="h-3 w-40" />
        <Skeleton className="h-5 w-2/3" />
        <Skeleton className="h-3 w-full" />
        <Skeleton className="h-3 w-5/6" />
      </div>
    );
  }

  // No expert bound to this folder: say so plainly and point at where to fix it.
  if (!expert) {
    return (
      <QuietNote className={className}>
        <span className="font-semibold text-fg">No expert is bound to this folder.</span> A folder expert writes the
        recurring topic briefing you would read here. <TextLink to="/experts">Create one in experts</TextLink>
      </QuietNote>
    );
  }

  const hasBriefing = Boolean(briefing?.success);
  const topics = asArray<ExpertTopic>(briefing?.topics);

  if (!hasBriefing) {
    return (
      <QuietNote className={className}>
        <span className="font-semibold text-fg">{expert.name}</span>
        <span className="mx-1.5 text-fg-3">·</span>
        {(briefing?.error || 'No briefing generated yet').replace(/\.\s*$/, '')}. Briefings are written on the experts
        page or by the scheduler; opening this track generates nothing. <TextLink to="/experts">Open experts</TextLink>
      </QuietNote>
    );
  }

  const issueDate = selectedDate || briefing?.end_date || null;
  const visibleHistory = history.slice(0, 14);

  return (
    <section aria-labelledby="track-briefing-title" className={cn('border-b border-line pb-8', className)}>
      <header>
        <p className="text-[0.8125rem] tabular-nums text-fg-3">
          {issueDate ? formatIssueLong(issueDate) : 'Latest issue'}
        </p>
        <div className="mt-1 flex items-start gap-3">
          <h2
            id="track-briefing-title"
            className="min-w-0 flex-1 break-words text-[1.375rem] font-semibold leading-[1.25] tracking-[-0.02em] text-fg"
          >
            {expert.name} briefing
          </h2>
          <div className="flex shrink-0 items-center gap-1">
            <Button
              variant="ghost"
              size="sm"
              onClick={() => setOpen((v) => !v)}
              aria-expanded={open}
              aria-controls="track-briefing-body"
            >
              {open ? 'hide' : 'show'}
            </Button>
            <Button
              variant="ghost"
              size="icon"
              onClick={() => void load()}
              aria-label="Reload briefing"
              title="Reload the stored briefing (does not generate a new one)"
            >
              <RefreshCw aria-hidden="true" />
            </Button>
          </div>
        </div>
        <p className="mt-1 flex min-w-0 flex-wrap items-center gap-x-1.5 gap-y-1 text-[0.8125rem] tabular-nums text-fg-2">
          <span>{plural(briefing?.posts_processed ?? 0, 'post')}</span>
          {briefing?.start_date && briefing?.end_date ? (
            <>
              <span aria-hidden="true" className="text-fg-3">·</span>
              <span>{formatIssueRange(briefing.start_date, briefing.end_date)}</span>
            </>
          ) : null}
          {topics.length > 0 ? (
            <>
              <span aria-hidden="true" className="text-fg-3">·</span>
              <span>{plural(topics.length, 'topic')}</span>
            </>
          ) : null}
          {briefing?.generator ? (
            <>
              <span aria-hidden="true" className="text-fg-3">·</span>
              <GeneratorBadge generator={briefing.generator} />
            </>
          ) : null}
        </p>

        {/* Past issues, newest first. Each is already stored, so switching costs nothing.
            Plain underlined dates (smol's "issues" list); the current one is bold, no underline. */}
        {history.length > 1 ? (
          <nav aria-label="Past issues" className="mt-3 flex flex-wrap items-baseline gap-x-1 gap-y-1 text-[0.8125rem]">
            <span className="mr-1 text-fg-3">issues</span>
            {visibleHistory.map((entry, index) => {
              const date = (entry.end_date || entry.subject_key || '') as string;
              const isActive = date === selectedDate;
              const stub = entry.generator === 'fallback';
              return (
                <span key={entry.id} className="inline-flex items-baseline">
                  {index > 0 ? <span aria-hidden="true" className="mr-1 text-fg-3">/</span> : null}
                  <button
                    type="button"
                    onClick={() => void selectDate(date)}
                    disabled={switching}
                    aria-current={isActive ? 'true' : undefined}
                    title={`${entry.posts_processed ?? '?'} posts · ${entry.generator ?? 'unknown generator'}`}
                    className={cn(
                      'whitespace-nowrap rounded-sm tabular-nums disabled:opacity-50 coarse:min-h-[2.75rem]',
                      'focus-visible:outline focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-fg',
                      isActive ? 'font-semibold text-fg' : 'text-link text-fg-2',
                      stub && !isActive && 'decoration-dashed',
                    )}
                  >
                    {formatIssueShort(date)}
                    {stub ? <span className="text-fg-3"> (stub)</span> : null}
                  </button>
                </span>
              );
            })}
          </nav>
        ) : null}
      </header>

      {open && (
        <div
          id="track-briefing-body"
          aria-busy={switching || undefined}
          className={cn('mt-6 max-w-reading', switching && 'opacity-50')}
        >
          {briefing?.briefing && (
            <div className="min-w-0 break-words text-[1.0625rem] leading-[1.7] text-fg [overflow-wrap:anywhere]">
              <Suspense fallback={<p className="whitespace-pre-wrap">{briefing.briefing}</p>}>
                <MarkdownRenderer content={briefing.briefing} />
              </Suspense>
            </div>
          )}
          {topics.length > 0 && (
            <div className="mt-8">
              <h3 className="mb-4 text-[1.0625rem] font-semibold tracking-[-0.01em] text-fg">Topics</h3>
              <ol className="list-none text-[0.9375rem] leading-[1.6]">
                {topics.map((topic, i) => (
                  <TopicItem key={`${topic.title}-${i}`} topic={topic} index={i} />
                ))}
              </ol>
            </div>
          )}
        </div>
      )}
    </section>
  );
}
